const { withProjectBuildGradle } = require('@expo/config-plugins');

const START_MARKER = '// @generated begin drowsyguard-windows-native-build';
const END_MARKER = '// @generated end drowsyguard-windows-native-build';
const GENERATED_BLOCK = `${START_MARKER}
// Ninja bundled with CMake 3.22.1 cannot stat long prefab paths on Windows.
// Keep these modules' generated caches short and outside the temporary build directory.
if (System.getProperty('os.name').toLowerCase().contains('windows')) {
    def nativeBuildCaches = [
        'react-native-worklets-core': 'worklets',
        'react-native-vision-camera': 'camera'
    ]
    subprojects { nativeProject ->
        def cacheName = nativeBuildCaches[nativeProject.name]
        if (cacheName != null) {
            nativeProject.plugins.withId('com.android.library') {
                nativeProject.extensions.getByName('androidComponents').finalizeDsl { androidDsl ->
                    androidDsl.externalNativeBuild.cmake.buildStagingDirectory = new File(rootProject.projectDir, '.cxx/' + cacheName)
                }
            }
        }
    }
}
${END_MARKER}`;

// android/ is generated by Expo; keep the Gradle setting through every prebuild.
module.exports = function withWindowsNativeBuild(config) {
  return withProjectBuildGradle(config, (mod) => {
    if (mod.modResults.language !== 'groovy') {
      throw new Error('withWindowsNativeBuild requires the Expo Groovy project build.gradle template.');
    }

    const contents = mod.modResults.contents;
    const newline = contents.includes('\r\n') ? '\r\n' : '\n';
    const generatedBlock = GENERATED_BLOCK.replace(/\n/g, newline);
    const start = contents.indexOf(START_MARKER);
    const end = contents.indexOf(END_MARKER);

    if (start === -1 && end === -1) {
      const separation = contents.endsWith('\n') ? newline : `${newline}${newline}`;
      mod.modResults.contents = `${contents}${separation}${generatedBlock}${newline}`;
    } else {
      if (start === -1 || end < start || contents.indexOf(START_MARKER, start + START_MARKER.length) !== -1 || contents.indexOf(END_MARKER, end + END_MARKER.length) !== -1) {
        throw new Error('withWindowsNativeBuild found incomplete or duplicate generated markers in project build.gradle.');
      }
      mod.modResults.contents = `${contents.slice(0, start)}${generatedBlock}${contents.slice(end + END_MARKER.length)}`;
    }

    return mod;
  });
};
